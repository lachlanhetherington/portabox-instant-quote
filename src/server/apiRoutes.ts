// Proxy for Google Drive API
app.use('/api/drive', async (req, res) => {
  const token = req.headers.authorization;
  if (!token) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  const subPath = req.url.replace('/api/drive', '');
  if (!/^\/(upload\/)?drive\/v3\/files(\/[A-Za-z0-9_-]+)?(\?|$)/.test(subPath)) {
    return res.status(403).json({ error: 'Path not allowed' });
  }
  const url = `https://www.googleapis.com${subPath}`;
  
  try {
    const fetchOptions: RequestInit = {
      method: req.method,
      headers: {
        'Authorization': token,
        'Content-Type': req.headers['content-type'] || 'application/json',
      },
    };

    if (req.method !== 'GET' && req.method !== 'HEAD') {
      // For simplicity in this environment, we pipe the stream directly.
      // This requires the request to be readable as a stream.
      fetchOptions.body = req as any;
    }

    const response = await fetch(url, fetchOptions);
    
    // Pipe response back
    res.status(response.status);
    if (response.body) {
      // @ts-ignore
      for await (const chunk of response.body) {
        res.write(chunk);
      }
    }
    res.end();
  } catch (error) {
    res.status(500).json({ error: 'Failed to proxy request' });
  }
});

