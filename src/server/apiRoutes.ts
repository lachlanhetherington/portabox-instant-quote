// True Two-Way Sync Endpoint: Pulls latest rows from Smartsheet & Pushes unwritten rows from App
// Strictly locked to Dan Harrington's Phase I Sheet [ID: 3517583962886020]
app.post('/api/smartsheet/sync-dan-rows', async (req, res) => {
  const apiToken = smartsheetToken();
  if (!apiToken) return res.status(503).json({ success: false, error: SMARTSHEET_NOT_CONFIGURED });
  const targetSheetId = '3517583962886020';
  const incomingAppRows = Array.isArray(req.body.rows) ? req.body.rows : [];

  try {
    // 1. Fetch current live Smartsheet data (columns + rows) from 3517583962886020
    const sheetRes = await fetch(`https://api.smartsheet.com/2.0/sheets/${targetSheetId}?includeAll=true`, {
      headers: { Authorization: `Bearer ${apiToken}` },
    });

    if (!sheetRes.ok) {
      const err = await sheetRes.json().catch(() => ({}));
      return res.status(sheetRes.status).json({ success: false, error: err.message || 'Smartsheet sheet lookup failed' });
    }

    const sheetData = await sheetRes.json();
    const colMap = new Map<string, number>();
    const colTypeMap = new Map<number, string>();
    sheetData.columns?.forEach((col: any) => {
      colMap.set(col.title.toLowerCase().trim(), col.id);
      colTypeMap.set(col.id, col.type);
    });

    // 2. Parse live Smartsheet rows into structured app rows
    const pulledAppRows = parseSmartsheetRowsToAppRows(sheetData.rows || [], sheetData.columns || []);

    // 3. Find which incoming App rows need to be pushed to Smartsheet
    // Compare by Quote ID
    const existingQuoteIdsInSmartsheet = new Set(
      pulledAppRows.map((r) => String(r.quoteId || '').toLowerCase().trim()).filter(Boolean)
    );

    const rowsToPushToSmartsheet = incomingAppRows.filter((appRow: any) => {
      const qId = String(appRow.quoteId || appRow.orderNumber || '').toLowerCase().trim();
      return qId && !existingQuoteIdsInSmartsheet.has(qId);
    });

    let pushedCount = 0;
    let pushWarning: string | null = null;
    if (rowsToPushToSmartsheet.length > 0) {
      const smRowsToInsert = rowsToPushToSmartsheet.map((r: any) => ({
        toBottom: true,
        cells: mapAppRowToSmartsheetCells(r, colMap, colTypeMap),
      })).filter((item: any) => item.cells.length > 0);

      if (smRowsToInsert.length > 0) {
        const insertRes = await fetch(`https://api.smartsheet.com/2.0/sheets/${targetSheetId}/rows`, {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${apiToken}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify(smRowsToInsert),
        });

        if (insertRes.ok) {
          pushedCount = smRowsToInsert.length;
          console.log(`[Smartsheet Two-Way Sync] Pushed ${pushedCount} new quotes to Smartsheet sheet ${targetSheetId}`);
        } else {
          const insertErr = await insertRes.json().catch(() => ({}));
          console.warn('[Smartsheet Two-Way Sync] Row insert warning:', insertErr);
          pushWarning = insertErr.message || `Smartsheet row insert warning (${insertRes.status})`;
        }
      }
    }

    // If rows were pushed, re-fetch to return the fresh combined list
    let finalRows = pulledAppRows;
    if (pushedCount > 0) {
      const refreshedRes = await fetch(`https://api.smartsheet.com/2.0/sheets/${targetSheetId}?includeAll=true`, {
        headers: { Authorization: `Bearer ${apiToken}` },
      });
      if (refreshedRes.ok) {
        const refreshedData = await refreshedRes.json();
        finalRows = parseSmartsheetRowsToAppRows(refreshedData.rows || [], refreshedData.columns || []);
      }
    }

    return res.json({
      success: true,
      sheetId: String(targetSheetId),
      sheetName: sheetData.name,
      permalink: sheetData.permalink,
      totalRows: finalRows.length,
      pulledCount: pulledAppRows.length,
      pushedCount,
      pushWarning,
      rows: finalRows,
    });
  } catch (err: any) {
    console.error('Error during Smartsheet two-way sync:', err);
    return res.status(500).json({ success: false, error: err.message || 'Failed to sync rows with Smartsheet' });
  }
});

